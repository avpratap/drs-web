import type { ResourceProps } from "@refinedev/core";

const crud = (
  name: string,
  base: string,
  label: string,
  opts: { create?: boolean; edit?: boolean; show?: boolean } = {},
): ResourceProps => ({
  name,
  list: base,
  ...(opts.create ? { create: `${base}/create` } : {}),
  ...(opts.edit ? { edit: `${base}/:id/edit` } : {}),
  ...(opts.show ? { show: `${base}/:id` } : {}),
  meta: { label },
});

